package io.github.sanamhub.nepdate.codegen

import kotlinx.serialization.SerializationException
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.intOrNull
import kotlinx.serialization.json.jsonObject
import java.nio.file.Files
import java.nio.file.Path
import kotlin.io.path.readText

const val PATRO_SUMMARY = "shared/spec/vectors/patro-summary.json"
private const val SUMMARY_SCHEMA = 1

/** The hub's counts for the vendored patro data, read from [PATRO_SUMMARY] (PATRO section 3). */
data class PatroSummary(
    val firstYear: Int,
    val lastYear: Int,
    val firstDay: String,
    val lastDay: String,
    val firstSerial: Int,
    val lastSerial: Int,
    val days: Int,
    val tithiFirstDay: String,
    val tithiLastDay: String,
    val tithiFirstSerial: Int,
    val tithiDays: Int,
    val tithiNames: Int,
    val holidays: Int,
    val eventDays: Int,
    val events: Int,
    val eventNames: Int,
    val names: Int,
    val nameBytes: Int,
)

/**
 * Reads [PATRO_SUMMARY] under [root]. The file is generated by the hub from the same data and
 * travels in `shared/`, so a missing one means `shared/` predates it and must be re-synced.
 */
fun readPatroSummary(root: Path): PatroSummary {
    val path = root.resolve(PATRO_SUMMARY)
    if (!Files.isRegularFile(path)) {
        throw CodegenException(
            "$PATRO_SUMMARY is missing: re-sync shared/ from the hub, which generates it with the data " +
                "(py tools/shared_sync.py <checkout>)",
        )
    }
    val json = parsePatroSummary(path)
    val schema = summaryNumber(json, "schema")
    if (schema != SUMMARY_SCHEMA) throw CodegenException("$PATRO_SUMMARY: schema is $schema, expected $SUMMARY_SCHEMA")
    return PatroSummary(
        firstYear = summaryNumber(json, "first_year"),
        lastYear = summaryNumber(json, "last_year"),
        firstDay = summaryText(json, "first_day"),
        lastDay = summaryText(json, "last_day"),
        firstSerial = summaryNumber(json, "first_serial"),
        lastSerial = summaryNumber(json, "last_serial"),
        days = summaryNumber(json, "days"),
        tithiFirstDay = summaryText(json, "tithi_first_day"),
        tithiLastDay = summaryText(json, "tithi_last_day"),
        tithiFirstSerial = summaryNumber(json, "tithi_first_serial"),
        tithiDays = summaryNumber(json, "tithi_days"),
        tithiNames = summaryNumber(json, "tithi_names"),
        holidays = summaryNumber(json, "holidays"),
        eventDays = summaryNumber(json, "event_days"),
        events = summaryNumber(json, "events"),
        eventNames = summaryNumber(json, "event_names"),
        names = summaryNumber(json, "names"),
        nameBytes = summaryNumber(json, "name_bytes"),
    )
}

private fun parsePatroSummary(path: Path): JsonObject =
    try {
        Json.parseToJsonElement(path.readText()).jsonObject
    } catch (e: SerializationException) {
        throw CodegenException("$PATRO_SUMMARY: ${e.message}", e)
    } catch (e: IllegalStateException) {
        throw CodegenException("$PATRO_SUMMARY: ${e.message}", e)
    }

private fun summaryNumber(
    json: JsonObject,
    field: String,
): Int =
    (json[field] as? JsonPrimitive)?.takeIf { !it.isString }?.intOrNull
        ?: throw CodegenException("$PATRO_SUMMARY: $field is missing or not a number")

private fun summaryText(
    json: JsonObject,
    field: String,
): String =
    (json[field] as? JsonPrimitive)?.takeIf { it.isString }?.content
        ?: throw CodegenException("$PATRO_SUMMARY: $field is missing or not a string")

/** Fails when a count or range edge derived from the data differs from [summary]. */
fun validatePatroSummary(
    data: PatroTablesData,
    summary: PatroSummary,
    calendar: CalendarData,
) {
    val lastSerial = data.baseSerial + data.span - 1
    val tithiFirstSerial = data.baseSerial + data.tithiFirstOffset
    val tithiLastSerial = tithiFirstSerial + data.tithiIndex.size - 1
    val first = dateOfSerial(calendar, data.baseSerial)
    val last = dateOfSerial(calendar, lastSerial)
    val tithiFirst = dateOfSerial(calendar, tithiFirstSerial)
    val tithiLast = dateOfSerial(calendar, tithiLastSerial)
    val nameBytes =
        data.names.sumOf { pair ->
            pair.np.toByteArray(Charsets.UTF_8).size + pair.en.toByteArray(Charsets.UTF_8).size
        }

    fun count(
        field: String,
        shown: Int,
        actual: Int,
    ) {
        if (shown != actual) throw CodegenException("$PATRO_SUMMARY: $field is $shown, but the data gives $actual")
    }

    fun day(
        field: String,
        shown: String,
        actual: Triple<Int, Int, Int>,
    ) {
        val text = dayText(actual)
        if (shown != text) throw CodegenException("$PATRO_SUMMARY: $field is $shown, but the data gives $text")
    }

    count("first_year", summary.firstYear, first.first)
    count("last_year", summary.lastYear, last.first)
    day("first_day", summary.firstDay, first)
    day("last_day", summary.lastDay, last)
    count("first_serial", summary.firstSerial, data.baseSerial)
    count("last_serial", summary.lastSerial, lastSerial)
    count("days", summary.days, data.span)
    day("tithi_first_day", summary.tithiFirstDay, tithiFirst)
    day("tithi_last_day", summary.tithiLastDay, tithiLast)
    count("tithi_first_serial", summary.tithiFirstSerial, tithiFirstSerial)
    count("tithi_days", summary.tithiDays, data.tithiIndex.size)
    count("tithi_names", summary.tithiNames, data.tithiIndex.toSet().size)
    count("holidays", summary.holidays, data.holidays.size)
    count("event_days", summary.eventDays, data.eventDays.size)
    count("events", summary.events, data.eventNames.size)
    count("event_names", summary.eventNames, data.eventNames.toSet().size)
    count("names", summary.names, data.names.size)
    count("name_bytes", summary.nameBytes, nameBytes)
}

/** The BS date at [serial], from the calendar's month lengths. */
private fun dateOfSerial(
    calendar: CalendarData,
    serial: Int,
): Triple<Int, Int, Int> {
    var remaining = serial
    for (year in MIN_YEAR..MAX_YEAR) {
        val lengths = calendar.monthLengths[year - MIN_YEAR]
        val yearDays = lengths.sum()
        if (remaining < yearDays) {
            var month = 0
            while (remaining >= lengths[month]) {
                remaining -= lengths[month]
                month++
            }
            return Triple(year, month + 1, remaining + 1)
        }
        remaining -= yearDays
    }
    throw CodegenException("$PATRO_SUMMARY: serial $serial is outside BS $MIN_YEAR to $MAX_YEAR")
}

private fun dayText(day: Triple<Int, Int, Int>): String =
    "${day.first}-${day.second.toString().padStart(2, '0')}-${day.third.toString().padStart(2, '0')}"
