package io.github.sanamhub.nepdate.codegen

import org.junit.jupiter.api.io.TempDir
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.Paths
import kotlin.io.path.createDirectories
import kotlin.io.path.readBytes
import kotlin.io.path.readText
import kotlin.io.path.writeText
import kotlin.test.Test
import kotlin.test.assertContentEquals
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertFalse
import kotlin.test.assertTrue

class CodegenTest {
    @TempDir
    lateinit var root: Path

    private val repoRoot: Path =
        generateSequence(Paths.get("").toAbsolutePath()) { it.parent }
            .first { Files.exists(it.resolve("shared/VERSION")) }

    private val calendarJson: String = repoRoot.resolve(CALENDAR_JSON).readText()
    private val summaryJson: String = repoRoot.resolve(PATRO_SUMMARY).readText()

    private fun copyShared(
        json: String = calendarJson,
        summary: String = summaryJson,
    ) {
        val target = root.resolve(CALENDAR_JSON)
        target.parent.createDirectories()
        target.writeText(json)
        val patro = root.resolve(PATRO_DIR)
        patro.createDirectories()
        Files.list(repoRoot.resolve(PATRO_DIR)).use { files ->
            files.forEach { Files.copy(it, patro.resolve(it.fileName.toString())) }
        }
        val summaryTarget = root.resolve(PATRO_SUMMARY)
        summaryTarget.parent.createDirectories()
        summaryTarget.writeText(summary)
    }

    private fun json(transform: (String) -> String) = transform(calendarJson)

    @Test
    fun `generated file starts with the header and holds the year range`() {
        val text = renderCalendar(parseCalendar(calendarJson))
        assertTrue(text.startsWith("// Generated by :codegen. DO NOT EDIT.\n\npackage io.github.sanamhub.nepdate\n"))
        assertTrue("internal const val MIN_YEAR: Int = 1901\n" in text)
        assertTrue("internal const val MAX_YEAR: Int = 2199\n" in text)
        assertTrue(text.endsWith("\n"))
        assertFalse('\r' in text)
    }

    @Test
    fun `generated file holds the month lengths and epoch constants`() {
        val data = parseCalendar(calendarJson)
        val text = renderCalendar(data)
        assertTrue("internal const val EPOCH_UNIX_DAYS: Int = -45920\n" in text)
        assertTrue("internal const val EPOCH_WEEKDAY: Int = 4\n" in text)
        val rows = Regex(""""([0-3]{12})"(?: \+)? // (\d{4})""").findAll(text).toList()
        assertEquals(299, rows.size)
        assertEquals("1901", rows.first().groupValues[2])
        assertEquals("2199", rows.last().groupValues[2])
        val digits = rows.joinToString("") { it.groupValues[1] }
        assertEquals(3588, digits.length)
        val expected = data.monthLengths.flatten().joinToString("") { (it - 29).toString() }
        assertEquals(expected, digits)
    }

    @Test
    fun `running twice gives identical bytes`() {
        copyShared()
        assertEquals(0, runCodegen(root, check = false))
        val first = root.resolve(CALENDAR_OUTPUT).readBytes()
        val firstPatro = root.resolve(PATRO_OUTPUT).readBytes()
        assertEquals(0, runCodegen(root, check = false))
        assertContentEquals(first, root.resolve(CALENDAR_OUTPUT).readBytes())
        assertContentEquals(firstPatro, root.resolve(PATRO_OUTPUT).readBytes())
    }

    @Test
    fun `check passes on a fresh file and fails after a hand edit without writing`() {
        copyShared()
        runCodegen(root, check = false)
        assertEquals(0, runCodegen(root, check = true))
        val output = root.resolve(CALENDAR_OUTPUT)
        val edited = output.readText().replace("2199", "2200")
        output.writeText(edited)
        assertEquals(1, runCodegen(root, check = true))
        assertEquals(edited, output.readText())
    }

    @Test
    fun `check fails when the file is missing`() {
        copyShared()
        assertEquals(1, runCodegen(root, check = true))
        assertFalse(Files.exists(root.resolve(CALENDAR_OUTPUT)))
    }

    @Test
    fun `a missing summary asks for a resync`() {
        copyShared()
        Files.delete(root.resolve(PATRO_SUMMARY))
        val error = assertFailsWith<CodegenException> { runCodegen(root, check = false) }
        assertTrue("re-sync shared/" in error.message!!, error.message)
        assertFalse(Files.exists(root.resolve(CALENDAR_OUTPUT)))
    }

    @Test
    fun `a summary that disagrees with the data names the field and both values`() {
        copyShared(summary = summaryJson.replace(Regex(""""names": \d+"""), "\"names\": 0"))
        val error = assertFailsWith<CodegenException> { runCodegen(root, check = false) }
        assertTrue("names is 0" in error.message!!, error.message)
        assertTrue("data gives" in error.message!!, error.message)
        assertFalse(Files.exists(root.resolve(CALENDAR_OUTPUT)))
    }

    @Test
    fun `the committed file is up to date`() {
        assertEquals(0, runCodegen(repoRoot, check = true))
    }

    @Test
    fun `wrong min_year is rejected`() {
        val error =
            assertFailsWith<CodegenException> {
                parseCalendar(json { it.replace("\"min_year\": 1901", "\"min_year\": 1900") })
            }
        assertTrue("min_year" in error.message!!, error.message)
    }

    @Test
    fun `wrong max_year is rejected`() {
        val error =
            assertFailsWith<CodegenException> {
                parseCalendar(json { it.replace("\"max_year\": 2199", "\"max_year\": 2200") })
            }
        assertTrue("max_year" in error.message!!, error.message)
    }

    @Test
    fun `wrong epoch is rejected`() {
        val error =
            assertFailsWith<CodegenException> {
                parseCalendar(json { it.replace("\"ad\": \"1844-04-11\"", "\"ad\": \"1844-04-12\"") })
            }
        assertTrue("epoch" in error.message!!, error.message)
    }

    @Test
    fun `a year without 12 lengths is named`() {
        val error =
            assertFailsWith<CodegenException> {
                parseCalendar(json { it.replace("\"2050\": [31, ", "\"2050\": [") })
            }
        assertTrue("2050" in error.message!!, error.message)
    }

    @Test
    fun `a length outside 29 to 32 is named with its year`() {
        val line = Regex(""""2100": \[(\d+),""").find(calendarJson)!!
        val error =
            assertFailsWith<CodegenException> {
                parseCalendar(calendarJson.replace(line.value, "\"2100\": [33,"))
            }
        assertTrue("2100" in error.message!!, error.message)
    }

    @Test
    fun `a missing year is named`() {
        val line = Regex("""\s*"1999": \[[^]]*],""").find(calendarJson)!!
        val error = assertFailsWith<CodegenException> { parseCalendar(calendarJson.replace(line.value, "")) }
        assertTrue("1999" in error.message!!, error.message)
    }
}
