package io.github.sanamhub.nepdate

/** Days of the week, Sunday first as on Nepali calendars (ALGORITHM section 7: 0 = Sunday). */
public enum class Weekday {
    /** आइतवार. */
    SUNDAY,

    /** सोमवार. */
    MONDAY,

    /** मङ्गलवार. */
    TUESDAY,

    /** बुधवार. */
    WEDNESDAY,

    /** बिहिवार. */
    THURSDAY,

    /** शुक्रवार. */
    FRIDAY,

    /** शनिवार, the weekly holiday in Nepal. */
    SATURDAY,
}
